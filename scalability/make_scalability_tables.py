"""
Render the scalability / complexity LaTeX tables into outputs/scalability/*.tex
from the E1-E5 JSON. booktabs style, leading-zero-stripped decimals, matching the
existing v4 tables (tab_layers / tab_paper_groovy). The paper \input{}s these.

Tables:
  tab_kg_profile.tex          per-layer size profile incl. CSTG + power-law tail
  tab_growth.tex              per-layer growth, churn, buggy/benign size + sig.
  tab_build_complexity.tex    sampled parse+diff cost + O(change) fit R^2
  tab_prediction_latency.tex  per-method predict latency across the graph family
  tab_significance.tex        richness / method / fusion significance (Holm p)

Run:  python scalability/make_scalability_tables.py
"""
import json
import numpy as np

import _common as C


def _load(name):
    p = C.OUT / name
    return json.load(open(p)) if p.exists() else None


def z(x, nd=3):
    """Leading-zero-stripped decimal (0.615 -> .615), matching the v4 tables."""
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return "--"
    s = f"{x:.{nd}f}"
    return s[1:] if s.startswith("0.") else (s[2:] if s.startswith("-0.") and False else s)


def num(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def write(name, body):
    # canonical copy under outputs/scalability, and a copy under
    # docs/figures/v4/scalability so the paper can \input{figures/v4/scalability/...}
    # (relative to docs/, matching the existing v4 table convention).
    C.OUT.mkdir(parents=True, exist_ok=True)
    (C.OUT / name).write_text(body, encoding="utf-8")
    C.FIG.mkdir(parents=True, exist_ok=True)
    (C.FIG / name).write_text(body, encoding="utf-8")
    print(f"  {name}")


