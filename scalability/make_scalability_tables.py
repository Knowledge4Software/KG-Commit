def tab_cstg_graph_ablation(ga):
    """The online graph-inference ablation over separated CSTG hub-graph layers:
    5 methods x 5 variants, one block per headline metric, + the G channel row."""
    if not ga:
        return
    meta = ga["_meta"]
    variants = meta["variants"]
    vnames = {"core": "Core", "mentions": "+MENT.", "twidf": "+TW-IDF",
              "cooccurs": "+COOCC.", "full": "Full"}
    methods = meta["methods"]
    # one block per metric (Buggy-F1, Macro-F1, G-Mean, AUC, MCC) -- the 5 most
    # informative of the 7; Precision/Recall are summarised in the notebook.
    blocks = [("Buggy_F1", "Buggy-F1"), ("Macro_F1", "Macro-F1"),
              ("G_Mean", "G-Mean"), ("AUC", "AUC"), ("MCC", "MCC")]
    col_head = " & ".join(vnames[v] for v in variants)
    lines = []
    for key, pretty in blocks:
        lines.append(r"\multicolumn{" + str(len(variants) + 1) +
                     r"}{@{}l}{\textit{" + pretty + r"}}\\")
        for m in methods:
            cells = " & ".join(z(ga[v]["methods"][m][key], 3) for v in variants)
            lines.append(f"{m} & {cells} \\\\")
        # G channel is graph-independent: show as a single reference value
        if "G_channel" in ga:
            lines.append(r"\;\;G (feature clf.) & \multicolumn{" + str(len(variants)) +
                         r"}{c}{" + z(ga["G_channel"][key], 3) + r"} \\")
        lines.append(r"\midrule")
    if lines and lines[-1] == r"\midrule":
        lines.pop()                              # no rule directly before \bottomrule
    body = r"""% Auto-generated -- do not edit by hand.
\begin{table}[t]
\centering
\caption{CSTG \emph{online graph} ablation: the five final graph-inference methods
(RN, PPR, LP, DW, KGE) run fully online (prequential) over the CSTG's own graph
structure, one column per \emph{separated} CSTG hub-graph layer and one for the
full CSTG --- Core (file/dev hubs only), $+$MENTIONS (unweighted term hubs),
$+$TW-IDF (TextRank-weighted term hubs), $+$COOCCURS (adds the NPMI term--term
graph so walks diffuse through it), and Full CSTG (adds term-kind-typed edges).
The \emph{G (feature clf.)} row is the graph-independent CSTG feature classifier
under the same online protocol, for reference. All seven metrics are computed by
\texttt{online\_jit.final\_metrics}; five are shown here
(\texttt{scalability/cstg\_online\_graph\_ablation.py}).}
\label{tab:cstg-graph-ablation}
\begin{tabular}{@{}l""" + "r" * len(variants) + r"""@{}}
\toprule
Method & """ + col_head + r""" \\
\midrule
""" + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("tab_cstg_graph_ablation.tex", body)


def _final_fusion_delta():
    """Authoritative F vs F+G headline metrics from the final fusion run."""
    import pickle
    p = C.ROOT / "outputs" / "final_fusion_results.pkl"
    if not p.exists():
        return None
    d = pickle.load(open(p, "rb"))
    try:
        F = d["part2"]["F"]["metrics"]; FG = d["part2"]["F+G"]["metrics"]
    except Exception:
        return None
    keys = [("ROC-AUC", "ROC_AUC"), ("PR-AUC", "PR_AUC"),
            ("Macro-F1", "Macro_F1"), ("G-Mean", "G_Mean")]
    return {name: (F[k], FG[k]) for name, k in keys if k in F and k in FG}


def main():
    print("rendering tables ->", C.OUT)
    tab_kg_profile(_load("kg_profile.json"))
    tab_growth(_load("growth.json"))
    tab_build_complexity(_load("build_complexity.json"))
    tab_prediction_latency(_load("prediction_latency.json"))
    tab_significance(_load("significance.json"))
    tab_cstg_ablation(_load("cstg_ablation.json"))
    tab_cstg_graph_ablation(_load("cstg_graph_ablation.json"))
    print("done.")


if __name__ == "__main__":
    main()
