# ── T5 : significance ───────────────────────────────────────────────────────

def tab_significance(sig):
    if not sig:
        return
    rich_rows, ppr_rows, fus_rows = [], [], []
    rich = sig.get("richness_vs_core", {})
    for k, v in rich.items():
        if "final>Core" in k:
            m = k.split(":")[0]
            d = v["auc_a"] - v["auc_b"]
            rich_rows.append(f"{m}: final $>$ Core & {z(d,3)} & "
                             f"{_p(v.get('p_holm', v['p']))} \\\\")
    mc = sig.get("ppr_vs_others_final", {})
    for k, v in mc.items():
        d = v["roc_delong"]
        other = k.replace("PPR>", "").replace(" (final)", "")
        ppr_rows.append(f"PPR $>$ {other} & {z(d['auc_a']-d['auc_b'],3)} & "
                        f"{_p(d.get('p_holm', d['p']))} \\\\")
    # Deployed-model semantic effect: authoritative F vs F+G from the fusion run.
    ff = _final_fusion_delta()
    if ff:
        for metric, (f, fg) in ff.items():
            fus_rows.append(f"F+G $>$ F ({metric}) & {z(fg-f,3)} & "
                            f"{z(f,3)}$\\to${z(fg,3)} \\\\")

    body = r"""% Auto-generated -- do not edit by hand.
\begin{table}[t]
\centering
\caption{Statistical significance of the headline V4 comparisons. Rows in the
first two blocks use paired per-commit out-of-sample scores: $\Delta$AUC is the
ROC-AUC difference and $p$ is DeLong's paired test, Holm-corrected within each
block. The last block reports the deployed semantic-channel effect (F$+$G vs.\ F)
as the change in each headline metric from the final fusion run
(\code{run\_final\_fusion.py}).}
\label{tab:scal-sig}
\begin{tabular}{lrl}
\toprule
Comparison & $\Delta$ & $p$ (Holm) / value \\
\midrule
\multicolumn{3}{@{}l}{\textit{Graph richness helps (final graph vs.\ Core), $\Delta$AUC}}\\
""" + "\n".join(rich_rows) + r"""
\midrule
\multicolumn{3}{@{}l}{\textit{Best method on the final graph, $\Delta$AUC}}\\
""" + "\n".join(ppr_rows) + r"""
\midrule
\multicolumn{3}{@{}l}{\textit{Deployed semantic channel F$+$G vs.\ F}}\\
""" + "\n".join(fus_rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""
    write("tab_significance.tex", body)


